#!/usr/bin/env python3
"""Writes src/formats/korg_triton_gm.inc: the TRITON's GM program bank (256 programs) from its OS flash, as the numbers
korg_triton.cpp needs to play them from a TRITON content dump's ROM multisamples.

    gen_triton_gm.py <ext74092.710> > src/formats/korg_triton_gm.inc

ext74092.710 is the MAME korgtriton set's flash at 0x5c0000 (OS 1.0.92, sha1 def100dc06dc). The GM programs are 540-byte
PCG program records at 0xc0008 (266 of them: 128 GM, 128 variations, 9 GM drum kits, an init program; the kits and the
init program are left out). Offsets in a record, calibrated against 573 factory programs found both in the dump's
program cards and in 540-byte PCG banks:
    204         oscillator mode, low 2 bits: 0 single, 1 double, 2 drums
    OSC1 block (OSC2 = the same + 154):
    230 u16     high multisample (bit 15 a flag, not the number)   233 high level
    234 u16     low multisample                                    237 low level
    239         velocity multisample switch (this and up play the high one)
    240, 241    velocity zone bottom, top (double mode)
    262 s8      octave (x12 semitones)   263 s8 transpose   264 s8 tune (cents)
    276, 277 s8 pitch bend +, - (semitones)
    346         amp level   347 amp velocity intensity
    356..363    amp EG: start level, attack time, attack level, decay time, break point, slope time, sustain, release
    379         pan (low 7 bits; 0 random, 64 centre)
"""
import hashlib
import sys

BASE, SIZE, COUNT, OSC2 = 0xC0008, 540, 256, 154


def s8(b):
    return b - 256 if b > 127 else b


def osc(r, o):
    u16 = lambda at: int.from_bytes(r[o + at:o + at + 2], "big") & 0x7FFF
    return [u16(230), r[o + 233], u16(234), r[o + 237], r[o + 239], r[o + 240], r[o + 241],
            s8(r[o + 262]) * 12 + s8(r[o + 263]), s8(r[o + 264]), s8(r[o + 276]), s8(r[o + 277]),
            r[o + 346], r[o + 347], *r[o + 356:o + 364], r[o + 379] & 0x7F]


def main():
    d = open(sys.argv[1], "rb").read()
    sha = hashlib.sha1(d).hexdigest()
    out = sys.stdout
    out.write("// Generated by tests/gen_triton_gm.py from the TRITON OS 1.0.92 flash ext74092.710 (sha1 %s): the GM\n"
              "// program bank. Numbers only; the audio is the content dump's ROM multisamples.\n"
              "// name, mode (0 single, 1 double), then per oscillator: high multisample, level, low multisample, level,\n"
              "// velocity switch, velocity zone bottom, top, pitch (semitones), tune (cents), bend +, bend -, amp level,\n"
              "// amp velocity intensity, amp EG (start, attack time, attack level, decay time, break, slope time,\n"
              "// sustain, release), pan\n" % sha[:12])
    out.write("const TritonGm TRITON_GM[%d] = {\n" % COUNT)
    for k in range(COUNT):
        r = d[BASE + k * SIZE:BASE + (k + 1) * SIZE]
        name = r[:16].decode("ascii").rstrip()
        mode = r[204] & 3
        assert mode in (0, 1), (k, name, mode)
        oscs = [osc(r, 0), osc(r, OSC2) if mode == 1 else [0] * 22]
        body = ", ".join("{%s}" % ", ".join(map(str, o)) for o in oscs)
        out.write('    {"%s", %d, {%s}},\n' % (name.replace("\\", "\\\\").replace('"', '\\"'), mode, body))
    out.write("};\n")


if __name__ == "__main__":
    main()
